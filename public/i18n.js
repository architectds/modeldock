const TABLES = { en: I18N_EN, zh: I18N_ZH, ja: I18N_JA };
const SUPPORTED = Object.keys(TABLES);
// BCP-47 tags for documentElement.lang.
const HTML_LANG = { en: "en", zh: "zh-CN", ja: "ja" };

let currentLang = "en";
let t = (key, params) => {
  const table = TABLES[currentLang] || I18N_EN;
  let text = table[key] ?? I18N_EN[key] ?? key;
  if (params) for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, value);
  return text;
};

function setLang(lang) {
  currentLang = SUPPORTED.includes(lang) ? lang : "en";
  document.documentElement.lang = HTML_LANG[currentLang];
  try { localStorage.setItem("modeldock-lang", currentLang); } catch {}
  // The setup wizard (wizard.js) listens for this to re-render in the new
  // language; the dashboard re-applies static text via applyStaticI18n.
  try { window.dispatchEvent(new CustomEvent("modeldock:langchange")); } catch {}
}

function getLang() {
  return currentLang;
}

function supportedLangs() {
  return [...SUPPORTED];
}

function initI18n() {
  let lang = null;
  try { lang = localStorage.getItem("modeldock-lang"); } catch {}
  if (!SUPPORTED.includes(lang)) {
    // Match the browser preference on the primary subtag (zh-TW -> zh, fr-CA -> fr).
    const primary = (navigator.language || "en").toLowerCase().split("-")[0];
    lang = SUPPORTED.includes(primary) ? primary : "en";
  }
  setLang(lang);
  applyStaticI18n();
  if (typeof refreshDynamicText === "function") refreshDynamicText();
}

function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
  // Rail labels wrap or clip at 88px, so the tooltip carries the full string.
  // The visible label is the accessible name; setting aria-label here too
  // would just shadow it with the same text.
  document.querySelectorAll("[data-i18n-title]").forEach((node) => {
    node.title = t(node.dataset.i18nTitle);
  });
}

export { t, getLang, setLang, supportedLangs, initI18n, applyStaticI18n };
